-- Logistica - separacao operacional persistida.
--
-- O fechamento multicanal deixa de existir apenas dentro do estado estatico do
-- n8n: cada execucao vira um documento imutavel, pronto para consulta,
-- reimpressao e auditoria no Oraculo. O worker continua sendo o unico escritor;
-- usuarios autenticados leem sob RLS e toda acao de escrita passa por Server
-- Action depois de assertTabAccess('logistica').

begin;

set local lock_timeout = '5s';
set local statement_timeout = '120s';

create table public.logistica_picking_cursor (
  operation_id text primary key default 'uberlandia'
    check (operation_id = 'uberlandia'),
  last_cursor_end timestamptz,
  last_slot_key text,
  updated_at timestamptz not null default now()
);

create table public.logistica_picking_listas (
  id uuid primary key default gen_random_uuid(),
  operation_id text not null default 'uberlandia'
    check (operation_id = 'uberlandia'),
  kind text not null check (kind in ('official', 'custom')),
  trigger_source text not null
    check (trigger_source in ('schedule', 'refresh_button', 'custom_form')),
  status text not null default 'pending'
    check (status in ('pending', 'syncing', 'processing', 'ready', 'blocked', 'failed')),
  slot_key text,
  cursor_start timestamptz not null,
  cursor_end timestamptz not null,
  period_start timestamptz not null,
  period_end timestamptz not null,
  requested_by uuid,
  requested_by_email text,
  generated_at timestamptz,
  olist_sync_finished_at timestamptz,
  orders_count integer not null default 0 check (orders_count >= 0),
  orders_without_items integer not null default 0 check (orders_without_items >= 0),
  rows_count integer not null default 0 check (rows_count >= 0),
  units_sold numeric not null default 0 check (units_sold >= 0),
  boxes_total numeric not null default 0 check (boxes_total >= 0),
  loose_units_total numeric not null default 0 check (loose_units_total >= 0),
  marketplace_count integer not null default 0 check (marketplace_count >= 0),
  unmapped_count integer not null default 0 check (unmapped_count >= 0),
  whatsapp_status text not null default 'not_requested'
    check (whatsapp_status in ('not_requested', 'pending', 'sent', 'failed')),
  whatsapp_sent_at timestamptz,
  last_error text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint logistica_picking_listas_interval_check
    check (cursor_end > cursor_start and period_end > period_start),
  constraint logistica_picking_listas_custom_window_check
    check (kind <> 'custom' or period_end - period_start <= interval '7 days'),
  constraint logistica_picking_listas_slot_check
    check ((kind = 'official' and slot_key is not null) or (kind = 'custom' and slot_key is null)),
  unique (id, operation_id)
);

create table public.logistica_picking_itens (
  id bigint generated by default as identity primary key,
  operation_id text not null default 'uberlandia'
    check (operation_id = 'uberlandia'),
  lista_id uuid not null,
  position integer not null check (position > 0),
  sku text,
  product text not null,
  description text not null,
  sold_quantity numeric not null check (sold_quantity >= 0),
  boxes numeric not null check (boxes >= 0),
  loose_units numeric not null check (loose_units >= 0),
  created_at timestamptz not null default now(),
  constraint logistica_picking_itens_lista_fk
    foreign key (lista_id, operation_id)
    references public.logistica_picking_listas (id, operation_id)
    on delete cascade,
  unique (lista_id, position)
);

create table public.logistica_picking_impressoes (
  id bigint generated by default as identity primary key,
  operation_id text not null default 'uberlandia'
    check (operation_id = 'uberlandia'),
  lista_id uuid not null,
  printed_by uuid,
  printed_by_email text,
  printed_at timestamptz not null default now(),
  constraint logistica_picking_impressoes_lista_fk
    foreign key (lista_id, operation_id)
    references public.logistica_picking_listas (id, operation_id)
    on delete cascade
);

create unique index logistica_picking_listas_official_slot_uidx
  on public.logistica_picking_listas (operation_id, slot_key)
  where kind = 'official';

create index logistica_picking_listas_history_idx
  on public.logistica_picking_listas (operation_id, created_at desc);

create unique index logistica_picking_listas_one_active_uidx
  on public.logistica_picking_listas (operation_id, kind)
  where status in ('pending', 'syncing', 'processing');

create index logistica_picking_itens_lista_idx
  on public.logistica_picking_itens (lista_id, position);

create index logistica_picking_impressoes_lista_idx
  on public.logistica_picking_impressoes (lista_id, printed_at desc);

alter table public.logistica_picking_cursor enable row level security;
alter table public.logistica_picking_listas enable row level security;
alter table public.logistica_picking_itens enable row level security;
alter table public.logistica_picking_impressoes enable row level security;

-- O gate da interface nao substitui a RLS. A permissao e conferida ao vivo em
-- auth.users para que a revogacao de Logistica tenha efeito mesmo com JWT
-- antigo, seguindo a mesma regra de operacao usada pelo restante do Oraculo.
create or replace function oraculo_private.can_access_operation_tab(
  p_operation text,
  p_tab text
)
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select case
    when coalesce(current_setting('request.jwt.claims', true), '') <> ''
      and (current_setting('request.jwt.claims', true)::jsonb->>'role') = 'service_role' then true
    when coalesce(current_setting('request.jwt.claims', true), '') = ''
      and current_setting('role') in ('none', 'postgres', 'service_role') then true
    else exists (
      select 1
      from auth.users u
      join public.oraculo_operations o on o.id = p_operation
      where u.id = auth.uid()
        and (u.banned_until is null or u.banned_until < now())
        and o.enabled
        and case
          when u.raw_app_meta_data ? 'operations' then
            u.raw_app_meta_data->'operations'->p_operation->>'enabled' = 'true'
          else
            p_operation = 'uberlandia'
        end
        and (
          lower(coalesce(u.email, '')) in ('juliano@oliverhome.com.br', 'oliveiros_cardoso@hotmail.com')
          or case
            when u.raw_app_meta_data ? 'operations' then
              coalesce(u.raw_app_meta_data->'operations'->p_operation->'tabs', '[]'::jsonb) ? p_tab
            else
              coalesce(u.raw_app_meta_data->'tabs', '[]'::jsonb) ? p_tab
          end
        )
    )
  end;
$$;

revoke all on function oraculo_private.can_access_operation_tab(text, text) from public, anon;
grant execute on function oraculo_private.can_access_operation_tab(text, text) to authenticated, service_role;

revoke all on public.logistica_picking_cursor from public, anon, authenticated;
revoke all on public.logistica_picking_listas from public, anon, authenticated;
revoke all on public.logistica_picking_itens from public, anon, authenticated;
