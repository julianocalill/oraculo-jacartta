revoke all on sequence public.logistica_picking_itens_id_seq from public, anon, authenticated;
revoke all on sequence public.logistica_picking_impressoes_id_seq from public, anon, authenticated;

grant all on public.logistica_picking_cursor to service_role;
grant all on public.logistica_picking_listas to service_role;
grant all on public.logistica_picking_itens to service_role;
grant all on public.logistica_picking_impressoes to service_role;
